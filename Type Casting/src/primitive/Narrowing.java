package primitive;

public class Narrowing {
    public static void main(String args[]) {
    	float a=4.75f;
    	short b=(short)a;
    	
    	  System.out.println(a);
    	  System.out.println(b);
    	  
    	  double c=99.9;
    	  int d=(int)c;
    	  
    	  System.out.println(c);
    	  System.out.println(d);
    }
}
